CREATE TABLE users (
  id TEXT PRIMARY KEY,
  username TEXT NOT NULL UNIQUE CHECK (length(trim(username)) > 0),
  password_hash TEXT NOT NULL CHECK (length(password_hash) > 0),
  created_at TEXT NOT NULL DEFAULT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"'),
  role TEXT CHECK (role IN ('approver', 'applicant'))
);
CREATE UNIQUE INDEX users_role ON users(role) WHERE role IS NOT NULL;
CREATE TABLE sessions (token_hash TEXT PRIMARY KEY, user_id TEXT NOT NULL REFERENCES users(id), expires_at BIGINT NOT NULL);
CREATE TABLE relationships (id TEXT PRIMARY KEY, approver_id TEXT NOT NULL UNIQUE REFERENCES users(id), applicant_id TEXT NOT NULL UNIQUE REFERENCES users(id));
CREATE TABLE invitations (token_hash TEXT PRIMARY KEY, approver_id TEXT NOT NULL REFERENCES users(id), expires_at BIGINT NOT NULL, used INTEGER NOT NULL DEFAULT 0 CHECK(used IN (0,1)));

CREATE TABLE budget_versions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, relationship_id TEXT NOT NULL REFERENCES relationships(id),
  kind TEXT NOT NULL CHECK(kind IN ('daily','monthly')), amount INTEGER NOT NULL CHECK(amount BETWEEN 1 AND 100000000),
  categories TEXT NOT NULL, effective_date TEXT NOT NULL, reason TEXT NOT NULL,
  created_by TEXT NOT NULL REFERENCES users(id), created_at BIGINT NOT NULL
);
CREATE INDEX budget_lookup ON budget_versions(relationship_id,kind,effective_date,id);

CREATE TABLE expenses (
  id TEXT PRIMARY KEY, relationship_id TEXT NOT NULL REFERENCES relationships(id), user_id TEXT NOT NULL REFERENCES users(id),
  request_id TEXT NOT NULL, amount INTEGER NOT NULL CHECK(amount BETWEEN 1 AND 100000000), category TEXT NOT NULL,
  spent_on TEXT NOT NULL, note TEXT NOT NULL, created_at BIGINT NOT NULL,
  budget_applicable INTEGER NOT NULL CHECK(budget_applicable IN (0,1)), unapproved INTEGER NOT NULL CHECK(unapproved IN (0,1)),
  version INTEGER NOT NULL DEFAULT 1, deleted_at BIGINT, original_input TEXT, approval_id TEXT,
  UNIQUE(user_id,request_id)
);
CREATE INDEX expense_month ON expenses(relationship_id,spent_on,id);
CREATE TABLE expense_changes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, expense_id TEXT NOT NULL REFERENCES expenses(id), user_id TEXT NOT NULL REFERENCES users(id),
  request_id TEXT NOT NULL, kind TEXT NOT NULL CHECK(kind IN ('update','delete','refund')), input TEXT NOT NULL,
  reason TEXT NOT NULL, before_json TEXT NOT NULL, after_json TEXT NOT NULL,
  refund_amount INTEGER NOT NULL DEFAULT 0 CHECK(refund_amount>=0), refunded_on TEXT, created_at BIGINT NOT NULL,
  UNIQUE(user_id,request_id)
);
CREATE INDEX expense_change_history ON expense_changes(expense_id,id);

CREATE TABLE approvals (
  id TEXT PRIMARY KEY, relationship_id TEXT NOT NULL REFERENCES relationships(id), user_id TEXT NOT NULL REFERENCES users(id),
  request_id TEXT NOT NULL, input TEXT NOT NULL, amount INTEGER NOT NULL CHECK(amount BETWEEN 1 AND 100000000),
  category TEXT NOT NULL, spent_on TEXT NOT NULL, purpose TEXT NOT NULL, reason TEXT NOT NULL,
  status TEXT NOT NULL, opinion TEXT NOT NULL DEFAULT '', daily_over BIGINT NOT NULL, monthly_over BIGINT NOT NULL,
  created_at BIGINT NOT NULL, approved_at BIGINT, expired_from TEXT,
  kind TEXT NOT NULL DEFAULT 'purchase' CHECK(kind IN ('purchase','supplement')),
  expense_id TEXT REFERENCES expenses(id), expense_version INTEGER,
  UNIQUE(user_id,request_id)
);
CREATE INDEX approval_month ON approvals(relationship_id,spent_on,created_at);
CREATE UNIQUE INDEX pending_supplement ON approvals(expense_id) WHERE kind='supplement' AND status='pending';
ALTER TABLE expenses ADD CONSTRAINT expenses_approval_id_fkey FOREIGN KEY (approval_id) REFERENCES approvals(id) DEFERRABLE;
CREATE UNIQUE INDEX expense_approval ON expenses(approval_id) WHERE approval_id IS NOT NULL;
CREATE TABLE approval_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, approval_id TEXT NOT NULL REFERENCES approvals(id), actor_id TEXT REFERENCES users(id),
  request_id TEXT, input TEXT, action TEXT NOT NULL, opinion TEXT NOT NULL, created_at BIGINT NOT NULL,
  UNIQUE(actor_id,request_id)
);
CREATE TABLE approval_credits (
  credit_id BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,
  approval_id TEXT PRIMARY KEY REFERENCES approvals(id), expense_id TEXT NOT NULL REFERENCES expenses(id),
  amount INTEGER NOT NULL CHECK(amount>=0), spent_on TEXT NOT NULL
);
CREATE INDEX credit_expense ON approval_credits(expense_id);

CREATE TABLE messages (
  id TEXT PRIMARY KEY, recipient_id TEXT NOT NULL REFERENCES users(id), approval_id TEXT REFERENCES approvals(id),
  kind TEXT NOT NULL CHECK(kind IN ('approval','budget')), title TEXT NOT NULL, created_at BIGINT NOT NULL,
  scope TEXT CHECK(scope IN ('daily','monthly')), period TEXT, threshold INTEGER CHECK(threshold IN (80,100)), read_at BIGINT
);
CREATE INDEX message_recipient ON messages(recipient_id,created_at,id);
CREATE TABLE notification_preferences(user_id TEXT PRIMARY KEY REFERENCES users(id),push_enabled INTEGER NOT NULL CHECK(push_enabled IN (0,1)));
CREATE TABLE notification_thresholds(user_id TEXT NOT NULL REFERENCES users(id),scope TEXT NOT NULL,period TEXT NOT NULL,level INTEGER NOT NULL,PRIMARY KEY(user_id,scope,period));
CREATE TABLE push_devices (
  cid TEXT PRIMARY KEY,user_id TEXT NOT NULL REFERENCES users(id),session_hash TEXT NOT NULL REFERENCES sessions(token_hash) ON DELETE CASCADE,
  expires_at BIGINT NOT NULL,enabled INTEGER NOT NULL CHECK(enabled IN (0,1))
);
CREATE TABLE push_deliveries (
  id TEXT PRIMARY KEY,message_id TEXT NOT NULL REFERENCES messages(id),cid TEXT NOT NULL REFERENCES push_devices(cid) ON DELETE CASCADE,
  status TEXT NOT NULL CHECK(status IN ('pending','accepted','failed','skipped')),attempts INTEGER NOT NULL DEFAULT 0,next_attempt_at BIGINT NOT NULL,last_error TEXT,
  UNIQUE(message_id,cid)
);
CREATE INDEX push_pending ON push_deliveries(status,next_attempt_at);
